"""
CreditLens-AI
AI-Assisted Explanation Panel

Renders the Gemini explanation layer returned by the API
(``llm_explanation``). This panel presents Gemini's summary,
risk explanation, and suggested analyst actions. It does not
compute, infer, or alter the risk decision in any way — the
decision comes from ``risk_level`` / ``decision``, which are
passed straight through from the API response.
"""

from __future__ import annotations

import html
from typing import Any

import streamlit as st

from components.feature_names import replace_feature_names
from components.markup import render_html


def render_recommendation_panel(
    risk_level: str,
    decision: str,
    llm_explanation: dict[str, Any] | None,
) -> None:

    is_high = risk_level.strip().lower() == "high risk"

    css_class = "recommendation-high" if is_high else "recommendation-low"

    llm_explanation = llm_explanation or {}

    summary = llm_explanation.get("summary")
    risk_explanation = llm_explanation.get("risk_explanation")
    analyst_actions = llm_explanation.get("analyst_actions") or []

    render_html(
        """
        <div class="section-header">
            <div>
                <div class="section-label">
                    AI-ASSISTED EXPLANATION
                </div>

                <div class="section-title">
                    Model Explanation Summary
                </div>
            </div>
        </div>
        """)

    if not summary and not risk_explanation and not analyst_actions:

        render_html(
            """
            <div class="empty-panel">

                <div class="empty-panel-title">
                    No explanation returned
                </div>

                <div class="empty-panel-text">
                    The explanation service did not return a
                    summary for this assessment.
                </div>

            </div>
            """)

        return

    body_parts: list[str] = [
        f'<div class="recommendation-panel {css_class}">',
        '<div class="section-label">DECISION GUIDANCE</div>',
        f'<div class="recommendation-title">{html.escape(decision)}</div>',
    ]

    if summary:
        body_parts.append(
            f'<div class="explanation-summary">'
            f"{html.escape(replace_feature_names(summary))}"
            f"</div>"
        )

    if risk_explanation:
        body_parts.append(
            '<div class="explanation-block-title">'
            "Risk Explanation"
            "</div>"
        )
        body_parts.append(
            f'<div class="explanation-text">'
            f"{html.escape(replace_feature_names(risk_explanation))}"
            f"</div>"
        )

    if analyst_actions:

        body_parts.append(
            '<div class="explanation-block-title">'
            "Recommended Analyst Actions"
            "</div>"
        )

        action_items = "".join(
            f"""
            <li class="analyst-action-item">
                <span class="analyst-action-index">{index}</span>
                <span>{html.escape(replace_feature_names(str(action)))}</span>
            </li>
            """
            for index, action in enumerate(analyst_actions, start=1)
        )

        body_parts.append(
            f'<ul class="analyst-actions-list">{action_items}</ul>'
        )

    body_parts.append(
        """
        <div class="explanation-disclaimer">
            This explanation is generated by an AI explanation
            layer from the existing model result and evidence.
            It is an analyst-support narrative, not an
            independent credit decision.
        </div>
        """
    )

    body_parts.append("</div>")

    render_html(
        "".join(body_parts))
