-- ============================================================
-- CreditLens-AI
-- PostgreSQL Database Schema
-- ============================================================
--
-- This file defines the database structure used by CreditLens-AI.
-- It is intentionally separate from the SQLAlchemy ORM models.
--
-- Database:
--     creditlens_ai
--
-- Tables:
--     customers
--     predictions
--     model_predictions
--     risk_factors
--     model_versions
--
-- ============================================================


-- ============================================================
-- Customers
-- ============================================================

CREATE TABLE IF NOT EXISTS public.customers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    customer_id VARCHAR(100) NOT NULL UNIQUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_customers_customer_id
    ON public.customers (customer_id);


-- ============================================================
-- Predictions
-- ============================================================

CREATE TABLE IF NOT EXISTS public.predictions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    customer_id VARCHAR(100) NOT NULL,

    prediction INTEGER NOT NULL,

    risk_level VARCHAR(50) NOT NULL,

    decision VARCHAR(100) NOT NULL,

    probability DOUBLE PRECISION NOT NULL,

    ensemble_probability DOUBLE PRECISION NOT NULL,

    threshold DOUBLE PRECISION NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_predictions_customer
        FOREIGN KEY (customer_id)
        REFERENCES public.customers (customer_id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS ix_predictions_customer_id
    ON public.predictions (customer_id);

CREATE INDEX IF NOT EXISTS ix_predictions_created_at
    ON public.predictions (created_at);


-- ============================================================
-- Individual Model Predictions
-- ============================================================

CREATE TABLE IF NOT EXISTS public.model_predictions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    prediction_id INTEGER NOT NULL,

    model_name VARCHAR(50) NOT NULL,

    probability DOUBLE PRECISION NOT NULL,

    prediction INTEGER NULL,

    CONSTRAINT fk_model_predictions_prediction
        FOREIGN KEY (prediction_id)
        REFERENCES public.predictions (id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS ix_model_predictions_prediction_id
    ON public.model_predictions (prediction_id);


-- ============================================================
-- SHAP Risk Factors
-- ============================================================

CREATE TABLE IF NOT EXISTS public.risk_factors (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    prediction_id INTEGER NOT NULL,

    feature_name VARCHAR(255) NOT NULL,

    feature_value TEXT NULL,

    shap_value DOUBLE PRECISION NOT NULL,

    direction VARCHAR(30) NOT NULL,

    rank INTEGER NOT NULL,

    CONSTRAINT fk_risk_factors_prediction
        FOREIGN KEY (prediction_id)
        REFERENCES public.predictions (id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS ix_risk_factors_prediction_id
    ON public.risk_factors (prediction_id);


-- ============================================================
-- Model Versions
-- ============================================================

CREATE TABLE IF NOT EXISTS public.model_versions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    model_name VARCHAR(100) NOT NULL,

    version VARCHAR(100) NOT NULL,

    metadata JSONB NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_model_versions_model_name
    ON public.model_versions (model_name);


-- ============================================================
-- Schema complete
-- ============================================================


SELECT
    table_name,
    column_name,
    data_type,
    is_nullable
FROM information_schema.columns
WHERE table_schema = 'public'
  AND table_name IN (
      'customers',
      'predictions',
      'model_predictions',
      'risk_factors',
      'model_versions'
  )
ORDER BY table_name, ordinal_position;



SELECT
    tc.table_name,
    tc.constraint_name,
    tc.constraint_type,
    kcu.column_name,
    ccu.table_name AS foreign_table_name,
    ccu.column_name AS foreign_column_name
FROM information_schema.table_constraints AS tc
LEFT JOIN information_schema.key_column_usage AS kcu
    ON tc.constraint_name = kcu.constraint_name
    AND tc.table_schema = kcu.table_schema
LEFT JOIN information_schema.constraint_column_usage AS ccu
    ON tc.constraint_name = ccu.constraint_name
    AND tc.table_schema = ccu.table_schema
WHERE tc.table_schema = 'public'
  AND tc.table_name IN (
      'customers',
      'predictions',
      'model_predictions',
      'risk_factors',
      'model_versions'
  )
ORDER BY tc.table_name, tc.constraint_type, tc.constraint_name;



SELECT
    tablename,
    indexname,
    indexdef
FROM pg_indexes
WHERE schemaname = 'public'
  AND tablename IN (
      'customers',
      'predictions',
      'model_predictions',
      'risk_factors',
      'model_versions'
  )
ORDER BY tablename, indexname;