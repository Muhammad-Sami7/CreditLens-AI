from __future__ import annotations

from datetime import datetime

from pydantic import BaseModel, Field


# ============================================================
# Prediction Request
# ============================================================

class PredictionRequest(BaseModel):
    """
    Request payload for a single customer prediction.
    """

    customer_id: str

    features: dict[str, float | int | str | None]


# ============================================================
# Model Probabilities
# ============================================================

class ModelProbabilities(BaseModel):
    """
    Individual model probabilities.
    """

    lightgbm: float

    xgboost: float

    catboost: float


# ============================================================
# LLM Explanation
# ============================================================

class LLMExplanationResponse(BaseModel):
    """
    Natural-language explanation generated by the LLM.

    The LLM explains the existing ML prediction and SHAP
    evidence. It does not make or modify the credit decision.
    """

    summary: str = Field(
        description="Concise explanation of the final risk result."
    )

    risk_explanation: str = Field(
        description="Evidence-based explanation of the assigned risk level."
    )

    key_risk_factors: list[str] = Field(
        description="Important factors contributing toward higher risk."
    )

    protective_factors: list[str] = Field(
        description="Factors contributing toward lower risk."
    )

    analyst_actions: list[str] = Field(
        description="Suggested analyst actions based on the supplied evidence."
    )


# ============================================================
# SHAP Explanation (structured evidence)
# ============================================================

class ShapFactor(BaseModel):
    """
    One feature's SHAP contribution for this prediction.

    Positive ``shap_value`` pushes the model toward higher risk,
    negative toward lower risk. This is model contribution, not
    proof of causality. ``rank`` is the 1-based position within
    the list the factor appears in.
    """

    feature: str

    feature_value: float | int | str | None = None

    shap_value: float

    direction: str

    rank: int

    # How many of the three models (LightGBM, XGBoost, CatBoost)
    # push this feature the same way as the ensemble (0-3).
    models_agreeing: int | None = None


class ShapExplanation(BaseModel):
    """
    Structured SHAP evidence for the production ensemble.

    Contributions are the weighted combination of the SHAP values of
    LightGBM, XGBoost and CatBoost (production ensemble weights), in
    raw log-odds units. They are evidence of how the models scored the
    customer, not an additive breakdown of the calibrated probability.
    """

    base_value: float | None = None

    feature_count: int | None = None

    models_explained: list[str] = Field(default_factory=list)

    top_factors: list[ShapFactor]

    positive_factors: list[ShapFactor]

    negative_factors: list[ShapFactor]


# ============================================================
# Feature Completeness
# ============================================================

class FeatureCompleteness(BaseModel):
    """
    How many production features were actually supplied.

    ``missing_count`` counts production columns that were absent
    from the input (they are filled with NaN). ``null_count`` counts
    columns that were supplied but empty (null/NaN); null is a
    legitimate value, e.g. no bureau history.
    """

    expected_count: int

    provided_count: int

    missing_count: int

    null_count: int = 0



# ============================================================
# Prediction Response
# ============================================================

class PredictionResponse(BaseModel):
    """
    Complete credit-risk prediction response.

    Contains:
    - Production ML prediction
    - Business risk assessment
    - Individual model probabilities
    - LLM explanation
    """

    customer_id: str

    prediction: int

    risk_level: str

    decision: str

    probability: float

    ensemble_probability: float

    threshold: float

    model_probabilities: ModelProbabilities

    llm_explanation: LLMExplanationResponse

    # Additive, optional fields (existing fields are unchanged).

    prediction_id: int | None = None

    shap: ShapExplanation | None = None

    feature_completeness: FeatureCompleteness | None = None

    # Production ensemble weights per model, read from the same
    # configuration the predictor uses (models/ensemble_config.json).
    model_weights: dict[str, float] | None = None


# ============================================================
# Customer Prediction History
# ============================================================

class PredictionHistoryItem(BaseModel):
    """
    Summary-level record of one persisted prediction.
    """

    prediction_id: int

    prediction: int

    risk_level: str

    decision: str

    probability: float

    ensemble_probability: float

    threshold: float

    created_at: datetime


class CustomerPredictionHistoryResponse(BaseModel):
    """
    Persisted predictions for one customer, newest first.
    """

    customer_id: str

    predictions: list[PredictionHistoryItem]


# ============================================================
# Dashboard Summary
# ============================================================

class DashboardRecentAssessment(BaseModel):

    prediction_id: int

    customer_id: str

    prediction: int

    risk_level: str

    decision: str

    probability: float

    created_at: datetime


class DashboardSummaryResponse(BaseModel):
    """
    Aggregates over persisted predictions.

    ``average_probability`` is the mean calibrated probability,
    or null when there are no assessments.
    """

    total_assessments: int

    high_risk_assessments: int

    low_risk_assessments: int

    average_probability: float | None

    recent_assessments: list[DashboardRecentAssessment]


# ============================================================
# Customer Lookup
# ============================================================

class SampleCustomersResponse(BaseModel):
    """
    Customer IDs available for server-side assessment.
    """

    customer_ids: list[str]
